-- ============================================================================
-- PremiumPulse Snowflake Script 05: RBAC & Dynamic Data Masking
-- ============================================================================

USE ROLE SECURITYADMIN;

-- 1. Create Functional Business Roles
CREATE ROLE IF NOT EXISTS PP_ADMIN
    COMMENT = 'Full administrator with unmasked data access and DDL privileges';

CREATE ROLE IF NOT EXISTS PP_UNDERWRITER
    COMMENT = 'Underwriter reviewing unmasked driver risk profiles and quoting';

CREATE ROLE IF NOT EXISTS PP_VIEWER
    COMMENT = 'Application service user and viewer role with masked PII';

-- Role Hierarchy: Grant roles up to SYSADMIN
GRANT ROLE PP_ADMIN TO ROLE SYSADMIN;
GRANT ROLE PP_UNDERWRITER TO ROLE SYSADMIN;
GRANT ROLE PP_VIEWER TO ROLE PP_UNDERWRITER;

USE ROLE SYSADMIN;

-- 2. Grant Warehouse and Database Usage
GRANT USAGE ON WAREHOUSE PP_WH TO ROLE PP_ADMIN;
GRANT USAGE ON WAREHOUSE PP_WH TO ROLE PP_UNDERWRITER;
GRANT USAGE ON WAREHOUSE PP_WH TO ROLE PP_VIEWER;

GRANT USAGE ON DATABASE PREMIUMPULSE_DB TO ROLE PP_ADMIN;
GRANT USAGE ON DATABASE PREMIUMPULSE_DB TO ROLE PP_UNDERWRITER;
GRANT USAGE ON DATABASE PREMIUMPULSE_DB TO ROLE PP_VIEWER;

-- 3. Schema & Object Privileges (Principle of Least Privilege)
-- PP_VIEWER only accesses MART
GRANT USAGE ON SCHEMA PREMIUMPULSE_DB.MART TO ROLE PP_VIEWER;
GRANT SELECT ON ALL TABLES IN SCHEMA PREMIUMPULSE_DB.MART TO ROLE PP_VIEWER;
GRANT SELECT ON ALL VIEWS IN SCHEMA PREMIUMPULSE_DB.MART TO ROLE PP_VIEWER;
GRANT SELECT ON ALL DYNAMIC TABLES IN SCHEMA PREMIUMPULSE_DB.MART TO ROLE PP_VIEWER;

-- PP_UNDERWRITER accesses CURATED and MART
GRANT USAGE ON SCHEMA PREMIUMPULSE_DB.CURATED TO ROLE PP_UNDERWRITER;
GRANT SELECT ON ALL TABLES IN SCHEMA PREMIUMPULSE_DB.CURATED TO ROLE PP_UNDERWRITER;
GRANT USAGE ON SCHEMA PREMIUMPULSE_DB.MART TO ROLE PP_UNDERWRITER;
GRANT SELECT ON ALL TABLES IN SCHEMA PREMIUMPULSE_DB.MART TO ROLE PP_UNDERWRITER;

-- PP_ADMIN has full control
GRANT ALL PRIVILEGES ON DATABASE PREMIUMPULSE_DB TO ROLE PP_ADMIN;

-- 4. Dynamic Data Masking Policies for PII Protection
USE SCHEMA PREMIUMPULSE_DB.CURATED;

CREATE OR REPLACE MASKING POLICY CURATED.MASK_EMAIL AS (val STRING) RETURNS STRING ->
    CASE
        WHEN CURRENT_ROLE() IN ('PP_ADMIN', 'PP_UNDERWRITER') THEN val
        ELSE CONCAT(SUBSTR(val, 1, 2), '***@***.***')
    END;

CREATE OR REPLACE MASKING POLICY CURATED.MASK_NAME AS (val STRING) RETURNS STRING ->
    CASE
        WHEN CURRENT_ROLE() IN ('PP_ADMIN', 'PP_UNDERWRITER') THEN val
        ELSE CONCAT(SUBSTR(val, 1, 1), '***')
    END;

-- Apply Masking Policies to PII Columns
ALTER TABLE CURATED.DRIVERS MODIFY COLUMN email SET MASKING POLICY CURATED.MASK_EMAIL;
ALTER TABLE CURATED.DRIVERS MODIFY COLUMN full_name SET MASKING POLICY CURATED.MASK_NAME;
